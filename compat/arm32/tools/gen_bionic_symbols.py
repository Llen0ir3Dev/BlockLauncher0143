#!/usr/bin/env python3
"""Generate the static-bionic symbol registration file for the ARM32 guest.

The guest is linked statically against the Android NDK's bionic archives.
libminecraftpe.so imports libc/libm/libdl/libz symbols, but the in-tree
loader resolves imports by name and cannot see a dynamic symbol table in a
static executable.  This generator emits an explicit table that references
each imported symbol, which both registers its address and forces the linker
to pull the defining archive member into the guest binary.

Input : bionic_symbols.txt (one symbol per line)
Output: bionic_symbols.c
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
GUEST = HERE.parent / "guest"


def main() -> int:
    source = GUEST / "bionic_symbols.txt"
    target = GUEST / "bionic_symbols.c"
    if len(sys.argv) > 1:
        source = pathlib.Path(sys.argv[1])
    if len(sys.argv) > 2:
        target = pathlib.Path(sys.argv[2])

    names = [
        line.strip()
        for line in source.read_text().splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    names = sorted(set(names))
    if not names:
        print("error: no symbols in", source, file=sys.stderr)
        return 1

    out = []
    out.append("// Generated by compat/arm32/tools/gen_bionic_symbols.py. Do not edit.")
    out.append("//")
    out.append("// Every entry references a symbol provided by the static bionic")
    out.append("// archives (libc/libm/libdl/libz) so the in-tree loader can resolve the")
    out.append("// imports of the genuine ARM32 Minecraft library.")
    out.append("//")
    out.append("// Each symbol is bound to a unique C identifier through an assembler")
    out.append("// alias.  This avoids clashing with the (sometimes builtin) bionic")
    out.append("// declarations while still making the linker pull the defining archive")
    out.append("// member into the guest binary.")
    out.append("")
    out.append("#include <stdint.h>")
    out.append('#include "loader_symbols.h"')
    out.append("")
    out.append(f"// {len(names)} symbols")
    for name in names:
        out.append(f'extern void nexus_sym_{name}(void) __asm__("{name}");')
    out.append("")
    out.append("static void reference_bionic_symbols(void) {")
    for name in names:
        out.append(f"    (void)&nexus_sym_{name};")
    out.append("}")
    out.append("")
    out.append("static const nexus_symbol_entry g_bionic_symbols[] = {")
    for name in names:
        out.append(f'    {{"{name}", (void*)(uintptr_t)&nexus_sym_{name}}},')
    out.append("};")
    out.append("")
    out.append("void nexus_register_bionic_symbols(void) {")
    out.append("    // Ensure all symbols are pulled from the static archives.")
    out.append("    reference_bionic_symbols();")
    out.append("    nexus_loader_add_symbols(g_bionic_symbols,")
    out.append("                             sizeof(g_bionic_symbols) / sizeof(g_bionic_symbols[0]));")
    out.append("}")
    out.append("")
    target.write_text("\n".join(out))
    print(f"wrote {target} ({len(names)} symbols)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
